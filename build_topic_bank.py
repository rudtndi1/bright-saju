# 월/요일/띠 변형 자동 확장 함수
# ============================================================
def _extend(keywords, patterns):
    """patterns: (prefix, suffix) 리스트. 키워드마다 월/요일/띠 변형을 만들어 추가한다."""
    out = []
    for kw in keywords:
        out.append(kw)
    for kw in list(keywords):
        for prefix, suffix in patterns:
            out.append(f"{prefix}{kw}{suffix}")
    return out


def build():
    bank = OrderedDict()
    for main_cat, subs in CURATED.items():
        bank[main_cat] = OrderedDict()
        for sub, kws in subs.items():
            # 카테고리별로 자연스러운 변형 패턴 적용
            patterns = []
            if sub in ("오늘의 운세", "이사 날짜", "개업 날짜", "결혼 택일", "손없는날"):
                patterns = [(f"{m} ", "") for m in MONTHS] + [(f"{d} ", "") for d in WEEKDAYS]
            elif sub == "띠별 운세":
                patterns = [(f"{z} ", "") for z in ZODIAC]
            elif sub == "무료 궁합":
                patterns = [(f"{z} ", "") for z in ZODIAC[:6]]
            elif sub in ("작명", "이름풀이"):
                patterns = [(f"{YEAR}년 ", ""), ("남자아이 ", ""), ("여자아이 ", ""), ("쌍둥이 ", "")]
            elif sub in ("출산 준비", "이사 준비 체크리스트", "집들이 선물", "신혼집 준비",
                         "자취 필수템", "생활용품 추천", "결혼선물", "집들이선물",
                         "부모님선물", "명절선물"):
                patterns = [(f"{YEAR} ", ""), ("첫 ", ""), ("가성비 ", ""), ("추천 ", " 총정리")]
            expanded = _extend(kws, patterns)

            # 30개 이상 보장 + 중복 제거 + 순서 섞기 없이 유지
            seen, result = set(), []
            for k in expanded:
                k = k.strip()
                if k and k not in seen:
                    seen.add(k)
                    result.append(k)
                if len(result) >= 45:
                    break
            result = result[:45]

            bank[main_cat][sub] = [
                {"keyword": k, "used": False, "used_date": None, "blog_url": None}
                for k in result
            ]
    return bank


def main():
    bank = build()
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "topics.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(bank, f, ensure_ascii=False, indent=2)

    # 요약 출력
    total = 0
    print("=" * 50)
    print("소재 뱅크 생성 완료")
    print("=" * 50)
    for main_cat, subs in bank.items():
        for sub, items in subs.items():
            total += len(items)
            print(f"  {main_cat} / {sub}: {len(items)}개")
    print(f"\n총 키워드: {total}개")
    print(f"저장: {path}")


if __name__ == "__main__":
    main()
